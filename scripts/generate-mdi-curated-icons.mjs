import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const collection = JSON.parse(fs.readFileSync(path.join(root, "node_modules/@iconify-json/mdi/icons.json"), "utf8"));
const targets = [
  {
    exportName: "MENU_MDI_ICONS",
    output: "src/lib/menu-mdi-icons.generated.ts",
    sources: ["src/lib/menu-icons.ts"]
  },
  {
    exportName: "CATEGORY_MDI_ICONS",
    output: "src/features/settings/category/category-mdi-icons.generated.ts",
    sources: ["src/features/settings/category/category-icons.ts"]
  }
];

function ownValue(record, key) {
  return Object.prototype.hasOwnProperty.call(record, key) ? record[key] : undefined;
}

function applyAlias(icon, alias) {
  return iconData({
    ...icon,
    hFlip: Boolean(icon.hFlip) !== Boolean(alias.hFlip),
    rotate: ((icon.rotate ?? 0) + (alias.rotate ?? 0)) % 4,
    vFlip: Boolean(icon.vFlip) !== Boolean(alias.vFlip)
  });
}

function iconData(icon) {
  return Object.fromEntries(
    ["body", "height", "hFlip", "left", "rotate", "top", "vFlip", "width"]
      .filter((key) => icon[key] !== undefined)
      .map((key) => [key, icon[key]])
  );
}

function resolveIcon(name, visited = new Set()) {
  if (visited.has(name)) return null;
  const icon = ownValue(collection.icons, name);
  if (icon) {
    return iconData({
      height: collection.height ?? collection.width ?? 16,
      width: collection.width ?? collection.height ?? 16,
      ...icon
    });
  }

  const alias = collection.aliases ? ownValue(collection.aliases, name) : undefined;
  if (!alias) return null;
  visited.add(name);
  const parent = resolveIcon(alias.parent, visited);
  return parent ? applyAlias(parent, alias) : null;
}

function referencedNames(sources) {
  const names = new Set();
  for (const source of sources) {
    const text = fs.readFileSync(path.join(root, source), "utf8");
    for (const match of text.matchAll(/mdi:([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(match[1]);
  }
  return [...names].sort();
}

function generateTarget(target) {
  const entries = referencedNames(target.sources)
    .map((name) => [name, resolveIcon(name)])
    .filter((entry) => entry[1]);
  const rows = entries.map(([name, icon]) => `  ${JSON.stringify(name)}: ${JSON.stringify(icon)}`);
  const content = [
    "// Generated by scripts/generate-mdi-curated-icons.mjs. Run it after changing curated icon values.",
    'import type { IconifyIcon } from "@iconify/react/offline";',
    "",
    `export const ${target.exportName}: Readonly<Record<string, IconifyIcon>> = {`,
    rows.join(",\n"),
    "};",
    ""
  ].join("\n");
  return { ...target, content };
}

const generated = targets.map(generateTarget);
const mode = process.argv[2] ?? "--json";

if (mode === "--check") {
  const stale = generated.filter(({ content, output }) => {
    const outputPath = path.join(root, output);
    return !fs.existsSync(outputPath) || fs.readFileSync(outputPath, "utf8").replaceAll("\r\n", "\n") !== content;
  });
  if (stale.length) {
    console.error(`Stale generated MDI files: ${stale.map((item) => item.output).join(", ")}`);
    process.exit(1);
  }
} else if (mode === "--write") {
  generated.forEach(({ content, output }) => fs.writeFileSync(path.join(root, output), content));
} else if (mode === "--json") {
  process.stdout.write(JSON.stringify(generated.map(({ content, output }) => ({ content, output }))));
} else if (mode.startsWith("--json=")) {
  const output = mode.slice("--json=".length);
  const target = generated.find((item) => item.output === output);
  if (!target) {
    console.error(`Unknown generated file: ${output}`);
    process.exit(1);
  }
  process.stdout.write(JSON.stringify({ content: target.content, output: target.output }));
} else {
  console.error(`Unknown mode: ${mode}`);
  process.exit(1);
}
